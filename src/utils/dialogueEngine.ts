/**
 * Natural Language Keyword Intent Classifier
 */
export function classifyUserIntent(text: string): UserIntent {
  const lower = text.toLowerCase().trim();

  // 1. 触抚精神体
  if (
    lower.includes('摸') || 
    lower.includes('揉') || 
    lower.includes('耳朵') || 
    lower.includes('尾巴') || 
    lower.includes('毛') || 
    lower.includes('精神体') ||
    lower.includes('肚皮') ||
    lower.includes('爪') ||
    lower.includes('羽毛') ||
    lower.includes('鬃毛') ||
    lower.includes('鳞片')
  ) {
    return '触抚精神体';
  }

  // 2. 询问状态
  if (
    lower.includes('状态') || 
    lower.includes('巡检') || 
    lower.includes('狂暴') || 
    lower.includes('精神海') || 
    lower.includes('波动') || 
    lower.includes('稳定') || 
    lower.includes('头疼') || 
    lower.includes('区间') ||
    lower.includes('阈值') ||
    lower.includes('还好吗') ||
    lower.includes('身体还好') ||
    lower.includes('有没有不适') ||
    lower.includes('感觉怎么样') ||
    lower.includes('失控')
  ) {
    return '询问状态';
  }

  // 3. 下达指令 / 邀约疏导
  if (
    lower.includes('预约') || 
    lower.includes('排期') || 
    lower.includes('来公馆') || 
    lower.includes('安抚舱') || 
    lower.includes('特约') || 
    lower.includes('见一面') || 
    lower.includes('过来') ||
    lower.includes('疏导') ||
    lower.includes('诊疗') ||
    lower.includes('什么时候有空') ||
    lower.includes('来找我') ||
    lower.includes('指令') ||
    lower.includes('命令')
  ) {
    return '下达指令';
  }

  // 4. 表达关心
  if (
    lower.includes('辛苦') || 
    lower.includes('注意休息') || 
    lower.includes('别太拼') || 
    lower.includes('逞强') || 
    lower.includes('伤') || 
    lower.includes('谢谢') || 
    lower.includes('感谢') ||
    lower.includes('注意安全') ||
    lower.includes('早点睡') ||
    lower.includes('心疼') ||
    lower.includes('别勉强') ||
    lower.includes('别硬撑')
  ) {
    return '表达关心';
  }

  // 5. 情绪倾诉 / 抱怨
  if (
    lower.includes('好累') || 
    lower.includes('想你') || 
    lower.includes('烦') || 
    lower.includes('开心') || 
    lower.includes('难受') || 
    lower.includes('委屈') ||
    lower.includes('无聊') ||
    lower.includes('头晕') ||
    lower.includes('叹气')
  ) {
    return '情绪倾诉';
  }

  // 6. 调情暧昧
  if (
    lower.includes('喜欢') || 
    lower.includes('乖') || 
    lower.includes('抱抱') || 
    lower.includes('只看你') || 
    lower.includes('笨蛋') || 
    lower.includes('心动') ||
    lower.includes('心跳') ||
    lower.includes('吃醋') ||
    lower.includes('想抱')
  ) {
    return '调情暧昧';
  }

  // 7. 严厉威慑 / 提及第三方
  if (
    lower.includes('老实') || 
    lower.includes('收敛') || 
    lower.includes('别打架') || 
    lower.includes('修罗场') || 
    lower.includes('听话') || 
    lower.includes('警告') || 
    lower.includes('吵') ||
    lower.includes('离他远点') ||
    lower.includes('不准乱来')
  ) {
    return '严厉威慑';
  }

  // 8. 日常问候
  if (
    lower.includes('在干嘛') || 
    lower.includes('在做什么') || 
    lower.includes('在忙吗') || 
    lower.includes('干嘛') || 
    lower.includes('早') || 
    lower.includes('晚上好') || 
    lower.includes('吃了吗') || 
    lower.includes('醒了吗') ||
    lower.includes('在吗') ||
    lower.includes('今天怎么样') ||
    lower.includes('哈喽') ||
    lower.includes('hi') ||
    lower.includes('hello')
  ) {
    return '日常问候';
  }

  return '闲聊问询';
}

/**
 * Determine affinity stage:
 * stage 1: 0 - 29 (陌生 / 刚认识 / 客套或警惕)
 * stage 2: 30 - 69 (好感阶段 / 信任建立 / 萌芽)
 * stage 3: 70 - 100 or Contracted (深爱 / 沉溺 / 极度独占)
 */
export function getAffinityStage(sentinel: Sentinel): 1 | 2 | 3 {
  if (sentinel.contracted || sentinel.affinity >= 70) return 3;
  if (sentinel.affinity >= 30) return 2;
  return 1;
}

