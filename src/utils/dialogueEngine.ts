/**
 * State and Condition Modifiers:
 * If riotRate >= 75: append or modify messages to convey tension, physical pain, and suppression
 * If timeOfDay === '下午' or evening: adapt time context
 */
function applyStateModifiers(
  burst: DialogueBurst,
  sentinel: Sentinel,
  timeOfDay?: TimeOfDay
): string[] {
  const result = [...burst.messages];

  // High Riot Modifier: Add a shivering / suppressed pain nuance if high riot
  if (sentinel.riotRate >= 75) {
    if (sentinel.personality === '阴湿') {
      result[0] = `……（手微颤地按住抽痛的太阳穴）${result[0]}`;
    } else if (sentinel.personality === '暴躁') {
      result[0] = `啧……额角神经突突地跳……${result[0]}`;
    } else if (sentinel.personality === '傲娇') {
      result[0] = `……头有点闷痛。${result[0]}`;
    } else if (sentinel.personality === '忠犬') {
      result[0] = `（强行压下精神域的尖锐震荡）${result[0]}`;
    } else if (sentinel.personality === '开朗') {
      result[0] = `哎呀，脑袋稍微有点发热呢！不过${result[0]}`;
    } else {
      result[0] = `……略有狂暴辐射反噬。${result[0]}`;
    }
  }

  // Time context hint occasionally if 1-message burst
  if (result.length === 1 && timeOfDay === '下午' && Math.random() > 0.6) {
    result.push(`前线已近黄昏，向导也要记得用晚餐。`);
  }

  return result;
}

/**
 * Core Dialogue Generator:
 * Returns an array of 1-3 strings representing sequential messages from the sentinel!
 */
export async function generateSentinelReply(
  sentinel: Sentinel,
  messageText: string,
  _contextHistory: ChatMessage[],
  _guide: Guide,
  timeOfDay?: TimeOfDay
): Promise<{ messages: string[]; intent: UserIntent }> {
  // [Future Extension Hook]:
  // If remote LLM is enabled, invoke server proxy / API:
  // if (ENABLE_LLM) { return await callGeminiLLM(sentinel, messageText, contextHistory, guide); }

  const intent = classifyUserIntent(messageText);
  const personality = sentinel.personality || '高冷';
  const stage = getAffinityStage(sentinel);

  const personalityGroup = BURST_LIBRARY[personality] || BURST_LIBRARY['高冷'];
  const intentGroup = personalityGroup[intent] || personalityGroup['闲聊问询'];
  const pool = intentGroup[stage] || intentGroup[2] || intentGroup[1];

  // Anti-repetition: Filter out candidates used recently
  if (!lastRepliesHistory[sentinel.id]) {
    lastRepliesHistory[sentinel.id] = [];
  }
  const history = lastRepliesHistory[sentinel.id];

  const available = pool.filter(b => !history.includes(b.messages.join('|')));
  const selectedBurst = available.length > 0
    ? available[Math.floor(Math.random() * available.length)]
    : pool[Math.floor(Math.random() * pool.length)];

  // Update history
  const signature = selectedBurst.messages.join('|');
  history.push(signature);
  if (history.length > 8) history.shift();

  // Apply real-time state modifiers (riot rate, time context)
  const finalMessages = applyStateModifiers(selectedBurst, sentinel, timeOfDay);

  return {
    messages: finalMessages,
    intent
  };
}
